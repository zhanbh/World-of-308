"""Controlled Boss HP sensitivity using v27 acquired gear; not a career replay."""
import argparse
import copy
import json
import statistics
from pathlib import Path

from first_dungeon_supply_path_trial import POTION, TIER, WEAR, reference
from spatial_growth_encounter_trial import run


def main():
    p=argparse.ArgumentParser()
    p.add_argument('--seed-start',type=int,default=0)
    p.add_argument('--seeds',type=int,default=12)
    p.add_argument('--output',type=Path,required=True)
    p.add_argument('--scales',type=float,nargs='+',default=[1,.9,.85])
    args=p.parse_args()
    assert args.seeds>0 and args.seed_start>=0
    assert args.scales and len(set(args.scales))==len(args.scales) and all(s>0 for s in args.scales)
    source=Path(__file__).parent/'results/first-dungeon-supply-path-v27.json'
    careers=json.loads(source.read_text(encoding='utf-8'))['traces']
    traces=[]
    for career in careers:
        if not args.seed_start<=career['seed']<args.seed_start+args.seeds:continue
        for level in (10,14):
            index=next(i for i,r in enumerate(career['path']) if r['entry_level']==level)
            assert index>0
            entry=career['path'][index]
            worn=copy.deepcopy(career['path'][index-1]['worn'])
            tier=TIER(level)
            context=dict(xp=0,loadout=worn,
                durability={k:v['durability']['current'] for k,v in worn.items() if k in WEAR},
                enemy_reference=reference(level),hp_restore=POTION[tier][0],mp_restore=POTION[tier][1],hp_count=8,mp_count=8)
            for scale in args.scales:
                r=run(level=level,gear='blue',seed=career['seed']*1000+entry['run']-1,
                      skill_policy=career['policy'],campaign=copy.deepcopy(context),boss_hp_scale=scale)
                traces.append(dict(career_seed=career['seed'],source_run=entry['run'],level=level,
                    policy=career['policy'],scale=scale,worn=worn,success=r['success'],seconds=r['seconds'],
                    boss_seconds=r['room_metrics'][-1]['seconds'] if len(r['room_metrics'])==7 else None,
                    hp_pots=r['hp_pots'],mp_pots=r['mp_pots'],room_metrics=r['room_metrics'],
                    potion_replacement_value=(r['hp_pots']+r['mp_pots'])*POTION[tier][2]))
            print(f"{career['policy']}/{career['seed']}/L{level}: done",flush=True)
    summaries=[]
    for policy in ('burst','mixed3_safe'):
        for level in (10,14):
            for scale in args.scales:
                rows=[r for r in traces if (r['policy'],r['level'],r['scale'])==(policy,level,scale)]
                assert len(rows)==args.seeds
                done=[r for r in rows if r['success']]
                summaries.append(dict(policy=policy,level=level,scale=scale,samples=len(rows),clears=len(done),
                    median_seconds=statistics.median(r['seconds'] for r in done) if done else None,
                    median_boss_seconds=statistics.median(r['boss_seconds'] for r in done) if done else None,
                    max_boss_seconds=max((r['boss_seconds'] for r in done),default=None),
                    boss_within_60=sum(r['boss_seconds']<=60 for r in done),
                    mean_hp_pots=statistics.mean(r['hp_pots'] for r in rows),
                    mean_mp_pots=statistics.mean(r['mp_pots'] for r in rows),
                    mean_replacement_value=statistics.mean(r['potion_replacement_value'] for r in rows)))
    width=len(args.scales)
    assert len(traces)==args.seeds*4*width
    for i in range(0,len(traces),width):
        group=traces[i:i+width]
        assert all(r['worn']==group[0]['worn'] for r in group)
        assert all(r['room_metrics'][:6]==group[0]['room_metrics'][:6] for r in group)
    output=dict(summaries=summaries,traces=traces,
        checks='PASS: acquired entry gear, paired fixtures, unchanged first six rooms, expected sample counts',
        limitations=['Entry XP reset to zero and eight current-tier HP/MP potions supplied: controlled comparison, NOT exact v27 replay or continuous economy.',
            'Gear is previous row post-town worn state, not current row post-town state; no gear generated by this experiment.',
            'Potion replacement value is candidate consumed-unit price, NOT actual spending, wallet or net income.',
            'Same encounter seed does not ensure common later hit RNG after changed combat duration.',
            'Only first dungeon normal at entry10/14, expected crit and scripted policies; no real-player validation or production changes.'])
    args.output.write_text(json.dumps(output,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')


if __name__=='__main__':main()
