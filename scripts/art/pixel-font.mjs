export function drawChar(canvas, x, y, char, r, g, b, a = 255, scale = 1) {
  const upper = char.toUpperCase();
  const rows = FONT_DATA[upper] || FONT_DATA[char] || FONT_DATA[' '];
  for (let row = 0; row < 7; row++) {
    const bits = rows[row];
    for (let col = 0; col < 5; col++) {
      if ((bits >> (4 - col)) & 1) {
        if (scale === 1) {
          canvas.setPixel(x + col, y + row, r, g, b, a);
        } else {
          canvas.fillRect(x + col * scale, y + row * scale, scale, scale, r, g, b, a);
        }
      }
    }
  }
}

export function drawText(canvas, x, y, text, r, g, b, a = 255, scale = 1, letterSpacing = 1) {
  let cx = x;
  for (let i = 0; i < text.length; i++) {
    drawChar(canvas, cx, y, text[i], r, g, b, a, scale);
    cx += (5 + letterSpacing) * scale;
  }
}
